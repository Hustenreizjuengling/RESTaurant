set define off

declare
    l_count pls_integer;
begin
    select count(*) into l_count from user_tables where table_name = 'DISHES';
    if l_count = 0 then
        execute immediate q'[
            create table dishes (
                dish_id     number generated by default on null as identity primary key,
                name        varchar2(100) not null,
                course      varchar2(20)  not null,
                price       number(6,2)   not null,
                vegetarian  varchar2(1)   default 'N' not null,
                created_on  date          default sysdate not null )]';
        execute immediate q'[
            create table reservations (
                reservation_id number generated by default on null as identity primary key,
                guest_name     varchar2(100) not null,
                seats          number(2)     not null,
                reserved_for   timestamp     not null,
                status         varchar2(20)  default 'REQUESTED' not null )]';
        execute immediate q'[insert into dishes (name, course, price, vegetarian) values ('Tomato soup', 'STARTER', 6.5, 'Y')]';
        execute immediate q'[insert into dishes (name, course, price, vegetarian) values ('Beef tartare', 'STARTER', 14, 'N')]';
        execute immediate q'[insert into dishes (name, course, price, vegetarian) values ('Mushroom risotto', 'MAIN', 17.5, 'Y')]';
        execute immediate q'[insert into dishes (name, course, price, vegetarian) values ('Sea bass', 'MAIN', 26, 'N')]';
        execute immediate q'[insert into dishes (name, course, price, vegetarian) values ('Creme brulee', 'DESSERT', 8, 'Y')]';
        execute immediate q'[insert into reservations (guest_name, seats, reserved_for) values ('Ada', 2, timestamp '2030-01-01 19:00:00')]';
    end if;
end;
/

declare
    l_roles    owa.vc_arr;
    l_patterns owa.vc_arr;
    l_modules  owa.vc_arr;
begin
    ords.enable_schema(
        p_enabled             => true,
        p_url_mapping_type    => 'BASE_PATH',
        p_url_mapping_pattern => lower(sys_context('userenv', 'current_schema')),
        p_auto_rest_auth      => false );

    ----------------------------------------------------------------------------
    -- menu.v1: public, read only
    ----------------------------------------------------------------------------
    ords.define_module(
        p_module_name    => 'menu.v1',
        p_base_path      => '/menu/v1/',
        p_items_per_page => 25,
        p_status         => 'PUBLISHED',
        p_comments       => 'Public menu of the restaurant' );

    ords.define_template(
        p_module_name => 'menu.v1',
        p_pattern     => 'dishes/',
        p_comments    => 'All dishes' );
    ords.define_handler(
        p_module_name => 'menu.v1',
        p_pattern     => 'dishes/',
        p_method      => 'GET',
        p_source_type => ords.source_type_collection_feed,
        p_source      => q'[select dish_id, name, course, price, vegetarian
  from dishes
 where course = nvl(upper(:course), course)
 order by course, name]',
        p_comments    => 'Optional filter: ?course=MAIN' );
    ords.define_parameter(
        p_module_name        => 'menu.v1',
        p_pattern            => 'dishes/',
        p_method             => 'GET',
        p_name               => 'course',
        p_bind_variable_name => 'course',
        p_source_type        => 'URI',
        p_param_type         => 'STRING',
        p_access_method      => 'IN',
        p_comments           => 'STARTER, MAIN or DESSERT' );

    ords.define_template(
        p_module_name => 'menu.v1',
        p_pattern     => 'dishes/:id',
        p_comments    => 'A single dish' );
    ords.define_handler(
        p_module_name => 'menu.v1',
        p_pattern     => 'dishes/:id',
        p_method      => 'GET',
        p_source_type => ords.source_type_collection_item,
        p_source      => q'[select dish_id, name, course, price, vegetarian, created_on
  from dishes
 where dish_id = :id]' );

    ----------------------------------------------------------------------------
    -- kitchen.v1: protected, read and write
    ----------------------------------------------------------------------------
    ords.define_module(
        p_module_name    => 'kitchen.v1',
        p_base_path      => '/kitchen/v1/',
        p_items_per_page => 50,
        p_status         => 'PUBLISHED',
        p_comments       => 'Back office services' );

    ords.define_template(
        p_module_name => 'kitchen.v1',
        p_pattern     => 'dishes/' );
    ords.define_handler(
        p_module_name   => 'kitchen.v1',
        p_pattern       => 'dishes/',
        p_method        => 'POST',
        p_source_type   => ords.source_type_plsql,
        p_mimes_allowed => 'application/json',
        p_source        => q'[begin
    insert into dishes (name, course, price, vegetarian)
    values (:name, upper(:course), :price, nvl(:vegetarian, 'N'))
    returning dish_id into :id;

    :status   := 201;
    :location := 'dishes/' || :id;
end;]' );
    ords.define_parameter('kitchen.v1', 'dishes/', 'POST', 'id', 'id', 'RESPONSE', 'INT', 'OUT');
    ords.define_parameter('kitchen.v1', 'dishes/', 'POST', 'X-ORDS-STATUS-CODE', 'status', 'HEADER', 'INT', 'OUT');
    ords.define_parameter('kitchen.v1', 'dishes/', 'POST', 'Location', 'location', 'HEADER', 'STRING', 'OUT');

    ords.define_template(
        p_module_name => 'kitchen.v1',
        p_pattern     => 'dishes/:id' );
    ords.define_handler(
        p_module_name   => 'kitchen.v1',
        p_pattern       => 'dishes/:id',
        p_method        => 'PUT',
        p_source_type   => ords.source_type_plsql,
        p_mimes_allowed => 'application/json',
        p_source        => q'[begin
    update dishes
       set name       = nvl(:name, name),
           price      = nvl(:price, price),
           vegetarian = nvl(:vegetarian, vegetarian)
     where dish_id = :id;

    :status := case when sql%rowcount = 0 then 404 else 200 end;
end;]' );
    ords.define_parameter('kitchen.v1', 'dishes/:id', 'PUT', 'X-ORDS-STATUS-CODE', 'status', 'HEADER', 'INT', 'OUT');
    ords.define_handler(
        p_module_name => 'kitchen.v1',
        p_pattern     => 'dishes/:id',
        p_method      => 'DELETE',
        p_source_type => ords.source_type_plsql,
        p_source      => q'[begin
    delete from dishes where dish_id = :id;
    :status := case when sql%rowcount = 0 then 404 else 204 end;
end;]' );
    ords.define_parameter('kitchen.v1', 'dishes/:id', 'DELETE', 'X-ORDS-STATUS-CODE', 'status', 'HEADER', 'INT', 'OUT');

    ords.define_template(
        p_module_name => 'kitchen.v1',
        p_pattern     => 'reservations/' );
    ords.define_handler(
        p_module_name => 'kitchen.v1',
        p_pattern     => 'reservations/',
        p_method      => 'GET',
        p_source_type => ords.source_type_collection_feed,
        p_source      => q'[select reservation_id, guest_name, seats, reserved_for, status
  from reservations
 order by reserved_for]' );

    ----------------------------------------------------------------------------
    -- security
    ----------------------------------------------------------------------------
    ords.create_role(p_role_name => 'kitchen_staff');

    l_roles(1)    := 'kitchen_staff';
    l_patterns(1) := '/kitchen/internal/*';
    l_modules(1)  := 'kitchen.v1';
    ords.define_privilege(
        p_privilege_name => 'kitchen.manage',
        p_roles          => l_roles,
        p_patterns       => l_patterns,
        p_modules        => l_modules,
        p_label          => 'Kitchen management',
        p_description    => 'Maintain dishes and see reservations',
        p_comments       => 'Sample privilege' );

    ----------------------------------------------------------------------------
    -- an OAuth client for the back office and an AutoREST table
    ----------------------------------------------------------------------------
    ords_security.register_client(
        p_name            => 'kitchen-display',
        p_grant_type      => 'client_credentials',
        p_support_email   => 'kitchen@example.com',
        p_description     => 'Screen in the kitchen that shows the reservations',
        p_privilege_names => 'kitchen.manage' );
    ords_security.grant_client_role(
        p_client_name => 'kitchen-display',
        p_role_name   => 'kitchen_staff' );

    ords.enable_object(
        p_enabled        => true,
        p_object         => 'RESERVATIONS',
        p_object_type    => 'TABLE',
        p_object_alias   => 'reservations',
        p_auto_rest_auth => true );

    commit;
end;
