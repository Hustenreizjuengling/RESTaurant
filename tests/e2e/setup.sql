--------------------------------------------------------------------------------
-- Prepares the sandbox for the end-to-end walkthrough. Run as SYS.
--
-- Creates the workspace E2E with two schemas that start without any REST
-- definitions, the workspace user TESTER and a table to build services on.
-- Everything in these two schemas is reset on every run.
--------------------------------------------------------------------------------
whenever sqlerror exit failure
set define off

declare
    procedure reset_schema (p_name in varchar2) is
        l_count pls_integer;
    begin
        select count(*) into l_count from dba_users where username = p_name;
        if l_count = 0 then
            execute immediate 'create user ' || p_name || ' identified by "Restaurant_4U" default tablespace users quota unlimited on users';
            execute immediate 'grant create session, create table, create view, create sequence, create procedure to ' || p_name;
        end if;
        -- remove all REST definitions of an earlier run
        select count(*) into l_count from dba_ords_schemas where parsing_schema = p_name;
        if l_count > 0 then
            ords_admin.drop_rest_for_schema(p_schema => p_name);
        end if;
        for t in ( select table_name from dba_tables where owner = p_name ) loop
            execute immediate 'drop table ' || p_name || '."' || t.table_name || '" cascade constraints purge';
        end loop;
        execute immediate 'create table ' || p_name || '.products (
            product_id  number generated by default on null as identity primary key,
            name        varchar2(100) not null,
            price       number(8,2)   not null,
            created_on  date default sysdate not null )';
        for i in 1 .. 7 loop
            execute immediate 'insert into ' || p_name || '.products (name, price) values (:1, :2)'
                using 'Product ' || i, i * 1.5;
        end loop;
    end reset_schema;
begin
    reset_schema('E2E_REST');
    reset_schema('E2E_REST_B');
    commit;
end;
/

declare
    l_count pls_integer;
begin
    select count(*) into l_count from apex_workspaces where workspace = 'E2E';
    if l_count = 0 then
        apex_instance_admin.add_workspace(
            p_workspace          => 'E2E',
            p_primary_schema     => 'E2E_REST',
            p_additional_schemas => 'E2E_REST_B');
    end if;
    apex_util.set_workspace('E2E');
    select count(*) into l_count
      from apex_workspace_apex_users
     where workspace_name = 'E2E' and user_name = 'TESTER';
    if l_count = 0 then
        apex_util.create_user(
            p_user_name                    => 'TESTER',
            p_email_address                => 'tester@example.com',
            p_web_password                 => 'Restaurant_4U',
            p_developer_privs              => 'ADMIN:CREATE:DATA_LOADER:EDIT:HELP:MONITOR:SQL',
            p_default_schema               => 'E2E_REST',
            p_change_password_on_first_use => 'N');
    end if;
    commit;
end;
/
exit
